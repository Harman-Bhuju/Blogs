from typing import Annotated

from fastapi import APIRouter, Depends
from sqlalchemy import select
from sqlalchemy.orm import Session

from blogs.core.database import get_db
from blogs.features.users.models import User as UserModel
from blogs.features.users.schemas import User as UserSchema

router = APIRouter(prefix="/users", tags=["users"])

DbSession = Annotated[Session, Depends(get_db)]


@router.get("/")
async def get_users(db: DbSession):
    statement = select(UserModel)
    # Returns the first selected item from each row.
    # Since we selected UserModel, it returns complete UserModel objects,
    # not just the first database column.
    users = db.scalars(statement).all()
    return users

@router.post("/")
async def create_user(user: UserSchema, db: DbSession):
        # Suppose the client sends:
    # {
    #     "name": "Harman",
    #     "email": "harman@example.com"
    # }

    # FastAPI/Pydantic creates a UserSchema object:
    # user = UserSchema(name="Harman", email="harman@example.com")


    # Pydantic object → dictionary
    # user.model_dump() converts:
    #
    # UserSchema(
    #     name="Harman",
    #     email="harman@example.com"
    # )
    #
    # into:
    #
    # {
    #     "name": "Harman",
    #     "email": "harman@example.com"
    # }

    data = user.model_dump()


    # Dictionary → SQLAlchemy object
    #
    # If data is:
    # {
    #     "name": "Harman",
    #     "email": "harman@example.com"
    # }
    #
    # The ** unpacks the dictionary, so this:
    #
    # UserModel(**data)
    #
    # becomes:
    #
    # UserModel(
    #     name="Harman",
    #     email="harman@example.com"
    # )
    #
    # Now db_user is a SQLAlchemy UserModel object.

    db_user = UserModel(**data)


    # Tell SQLAlchemy to track this UserModel object.
    # SQLAlchemy will later INSERT it into the database.
    #
    # Example:
    # db.add(db_user)

    db.add(db_user)


    # Commit the transaction.
    # This actually sends the INSERT to the database.
    #
    # Example SQL generated by SQLAlchemy:
    #
    # INSERT INTO users (name, email)
    # VALUES ('Harman', 'harman@example.com');

    db.commit()


    # Refresh db_user with the values from the database.
    #
    # This is useful if the database generated something for us,
    # such as an auto-incremented ID.
    #
    # Before refresh:
    # db_user.id = 1        # might already be available, depending on setup
    #
    # After refresh:
    # db_user.id = 1
    # db_user.name = "Harman"
    # db_user.email = "harman@example.com"

    db.refresh(db_user)


    # Return the SQLAlchemy object.
    # FastAPI can serialize it according to your response model.

    return db_user